import math


def area(r):
    """
    Вычисляет площадь круга.

    Параметры:
        r: радиус круга.

    Возвращаемое значение:
        Площадь круга.

    Пример вызова:
        area(3)
    """
    return math.pi * r * r


def perimeter(r):
    """
    Вычисляет длину окружности.

    Параметры:
        r: радиус круга.

    Возвращаемое значение:
        Длина окружности.

    Пример вызова:
        perimeter(3)
    """
    return 2 * math.pi * r
