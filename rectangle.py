# Вычисляет площадь прямоугольника по длинам сторон a и b.
# Пример вызова: area(3, 4) -> 12.
def area(a, b):
    """Возвращает площадь прямоугольника: a * b."""
    return a * b

# Вычисляет периметр прямоугольника по длинам сторон a и b.
# Пример вызова: perimeter(3, 4) -> 14.
def perimeter(a, b):
    """Возвращает периметр прямоугольника: 2 * (a + b)."""
    return 2 * (a + b)
