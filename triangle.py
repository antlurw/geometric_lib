# Вычисляет площадь треугольника по основанию a и высоте h.
# Пример вызова: area(3, 4) -> 6.0.
def area(a, h):
    '''Возвращает площадь треугольника: a * h / 2.'''
    return a * h / 2


# Вычисляет периметр треугольника по длинам сторон a, b и c.
# Пример вызова: perimeter(3, 4, 5) -> 12.
def perimeter(a, b, c):
    '''Возвращает сумму длин трёх сторон треугольника.'''
    return a + b + c