
def area(a):
    """
    Вычисляет площадь квадрата.

    Параметры:
        a: длина стороны квадрата.

    Возвращаемое значение:
        Площадь квадрата.

    Пример вызова:
        area(5)
    """
    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата.

    Параметры:
        a: длина стороны квадрата.

    Возвращаемое значение:
        Периметр квадрата.

    Пример вызова:
        perimeter(5)
    """
    return 4 * a
