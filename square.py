
# Вычисляет площадь квадрата по длине стороны a.
# Пример вызова: area(3) -> 9.
def area(a):
    '''Возвращает площадь квадрата: a * a.'''
    return a * a


# Вычисляет периметр квадрата по длине стороны a.
# Пример вызова: perimeter(3) -> 12.
def perimeter(a):
    '''Возвращает периметр квадрата: 4 * a.'''
    return 4 * a
